#!/usr/bin/env python3
"""Step A: monolayer strain grid.
   Instead of two monolayers for EVERY heterostructure, each monolayer is computed on a biaxial strain grid ε ∈ [-2,+2]% in 0.5% steps (9 points; the actual strains of the 7796 interfaces lie within -1.5..+1.6%)
   and interpolated at the common lattice constant of each interface -> 108×9 = 972 four-atom calculations instead of 2×7796.
   Each MONO/<name>/e<ε>/ directory: relax.in (z relaxation, fixed cell), pp.in, avg.in. The effective-mass step is generated by mono_mass.py after relaxation.
   Requires ASE (run locally), then copy MONO/ to the cluster.
   python3 mk_mono.py --names janus_table.csv [--strains -2:2:0.5] [--test]"""
import argparse, os, numpy as np, pandas as pd
from ase.io import read
from qeio import write_pw, pp_input, avg_input, SET
ap = argparse.ArgumentParser(); ap.add_argument("--names", default="janus_table.csv"); ap.add_argument("--s3", default="S3.extxyz")
ap.add_argument("--strains", default="-2:2:0.5"); ap.add_argument("--out", default="MONO"); ap.add_argument("--C", type=float, default=30.0)
ap.add_argument("--only", default=""); ap.add_argument("--test", action="store_true", help="ecut 40, k 6 (pipeline test only)")
a = ap.parse_args()
s = dict(SET, ecut=40.0, k=6, conv=1e-7) if a.test else SET
lo, hi, st = map(float, a.strains.split(":")); eps = np.round(np.arange(lo, hi + 1e-9, st), 3)
names = [n.replace("_M", "") for n in pd.read_csv(a.names).name]
if a.only: names = [n for n in names if n in a.only.split(",")]
S = {x.info["name"]: x for x in read(a.s3, ":")}
n = 0
for nm in names:
    m = S[nm]; a0 = np.linalg.norm(m.cell[0]); z = m.positions[:, 2]
    for e in eps:
        d = os.path.join(a.out, nm, "e%+.1f" % e); os.makedirs(d, exist_ok=True)
        x = m.copy(); cell = np.array(x.cell); cell[:2] *= (1 + e / 100); cell[2] = [0, 0, a.C]
        x.set_cell(cell, scale_atoms=False); fr = m.get_scaled_positions()[:, :2]
        pos = np.c_[fr @ cell[:2, :2], z - z.mean() + a.C / 2]
        write_pw(f"{d}/relax.in", "relax", x.get_chemical_symbols(), pos, cell, prefix="m", s=s, nbnd=None)
        pp_input(f"{d}/pp.in", "m"); avg_input(f"{d}/avg.in", "vtot.dat", 1500, a.C / 0.529177)
        open(f"{d}/meta.txt", "w").write(f"name {nm}\nstrain {e}\na0 {a0:.6f}\na {a0 * (1 + e / 100):.6f}\nkgrid {s['k']}\n")
        n += 1
print(f"{n} monolayer directories ({len(names)} compounds × {len(eps)} strains) in {a.out}/")
